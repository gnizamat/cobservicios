export interface Code39Bar {
  width: number
  black: boolean
}

export function code39Bars(value: string): Code39Bar[] {
  const text = `*${value.toUpperCase()}*`
  const bars: Code39Bar[] = []
  for (const char of text) {
    const pattern = PATTERNS[char]
    if (!pattern) continue
    for (let index = 0; index < pattern.length; index += 1) {
      bars.push({ width: pattern[index] === 'w' ? 3 : 1, black: index % 2 === 0 })
    }
    bars.push({ width: 1, black: false })
  }
  return bars
}
